## Two SI tables tying sigma_r (the population SD of log input rate, Fig 5's
## x-axis) to real input numbers:
##   out/sigma_r_ranges.tex   -- for sigma_r at the band edge, the three anchors
##                               and one value beyond the band: fold change per SD,
##                               the 10th-90th percentile range in words per waking
##                               hour at the reference rate, the 90th:10th ratio, and
##                               the implied input share of efficiency variance
##                               (English / Norwegian, analytic curve of Fig 5).
##   out/sigma_r_evidence.tex -- the channel-matched evidence: all-adult tokens per
##                               waking hour in Western samples -- literature rows
##                               with a computed within-sample SD of log rate
##                               (studies/input_estimation/validation_set.csv), this
##                               paper's four datasets (raw per-child SD), and the
##                               measurement model's noise-corrected estimate.
## Reads: paper/cache/fig_io_imputed_proc.rds, studies/input_estimation/validation_set.csv.
## Run:   Rscript paper/tables/sigma_r_tables.R
suppressPackageStartupMessages({library(here); library(dplyr); library(readr)})
OUT <- here("paper", "tables", "out"); dir.create(OUT, recursive = TRUE, showWarnings = FALSE)
io  <- readRDS(here("paper", "cache", "fig_io_imputed_proc.rds"))
a   <- io$panelA; ref <- a$input_ref$ref_rate
z90 <- qnorm(0.9)
num <- function(x, d = 0) format(round(x, d), big.mark = ",", trim = TRUE, nsmall = d)
tex <- function(x) gsub("&", "\\\\&", gsub("%", "\\\\%", x))

## ---- Table: sigma_r -> input ranges and shares ----
share <- function(model, sr) sapply(sr, function(s) a$curves$share[a$curves$model == model][which.min(abs(a$curves$sigma_r[a$curves$model == model] - s))])
rng <- tibble(sigma_r = c(0.32, 0.35, 0.44, 0.58, 0.80),
              role = c("lower edge of the band (direct estimate, lower 95\\% limit)",
                       "direct estimate from this paper's recordings (anchor)",
                       "raw within-sample SD in this paper's datasets; literature median (main anchor)",
                       "largest within-sample SD in the evidence (anchor)",
                       "beyond the band (for scale)")) |>
  mutate(per_sd = exp(sigma_r), lo = ref * exp(-z90 * sigma_r), hi = ref * exp(z90 * sigma_r),
         ratio = exp(2 * z90 * sigma_r),
         en = 100 * share("English (D)", sigma_r), no = 100 * share("Norwegian (D)", sigma_r))
lines1 <- c(
  sprintf("%% Generated by paper/tables/sigma_r_tables.R (reference rate %s words/h = geometric mean of the four datasets' geometric means) -- do not edit by hand.", num(ref)),
  "\\begin{tabular}{lp{5.2cm}rrrrr}", "\\toprule",
  sprintf("$\\sigma_r$ & Role & $\\times/\\div$ per SD & 10th--90th pct.\\ (words/h at %s) & 90th:10th & Share EN & Share NO \\\\", num(ref)),
  "\\midrule",
  sprintf("%.2f & %s & %.2f & %s--%s & %.1f & %.1f\\%% & %.1f\\%% \\\\",
          rng$sigma_r, rng$role, rng$per_sd, num(rng$lo, 0), num(rng$hi, 0), rng$ratio, rng$en, rng$no),
  "\\bottomrule", "\\end{tabular}")
writeLines(lines1, file.path(OUT, "sigma_r_ranges.tex"))

## ---- Table: the channel-matched evidence ----
v <- read_csv(here("studies", "input_estimation", "validation_set.csv"), show_col_types = FALSE)
lit <- v |>
  filter(measure_type == "all-adult", !is.na(log_r_sd),
         !grepl("^this paper|^Bergelson et al. 2018", source),          # our datasets: computed below
         !(grepl("Weisleder", source) & reported_or_computed == "computed-from-paper-data")) |>  # duplicate W&F row
  transmute(source = sub(" \\(.*", "", source), sample = sample_label, language,
            n = n_kids, method = case_when(grepl("LENA", method) ~ "LENA",
                                           grepl("transcript", method) ~ "transcript", TRUE ~ method),
            rate = tokens_per_hour_mean, sd = log_r_sd, block = "Literature")
ours <- a$input_ref$by_dataset |>
  transmute(source = "This paper", sample = dataset, language = "English (US)", n = n_children,
            method = if_else(dataset == "BabyView", "head-cam transcript", "LENA"),
            rate = gm_rate, sd = raw_sd, block = "This paper (raw per-child SD)")
single <- !grepl("pooled|combined", lit$sample, ignore.case = TRUE)   # independent samples only
lit_median <- median(lit$sd[single])
sr_model <- io$panelB |> filter(channel == "Efficiency", factor == "Input")   # sigma_r = input -> efficiency per SD
## one column for source + sample ("Sperry et al. (2019), Alabama") to keep the
## table inside a text column
SAMPLE <- c("All sites pooled" = "pooled", "Home + Daycare combined" = "combined",
            "low-SES Spanish-speaking" = "")            # the language column says it
LANG   <- c("English (US)" = "US English", "English (US, mixed)" = "US English",
            "English (CA, Manitoba)" = "Canadian English", "Spanish (US, low-SES)" = "US Spanish, low SES")
label <- function(d) {
  smp <- ifelse(d$sample %in% names(SAMPLE), SAMPLE[d$sample], d$sample)
  tex(ifelse(d$source == "This paper", d$sample,
             paste0(sub(" (\\d{4})$", " (\\1)", d$source), ifelse(smp == "", "", paste0(", ", smp)))))
}
row <- function(d) sprintf("%s & %s & %s & %s & %s & %.2f \\\\", label(d),
                           tex(ifelse(d$language %in% names(LANG), LANG[d$language], d$language)),
                           num(d$n), sub("head-cam transcript", "head-cam", d$method), num(d$rate), d$sd)
lines2 <- c(
  "% Generated by paper/tables/sigma_r_tables.R from studies/input_estimation/validation_set.csv + the io cache -- do not edit by hand.",
  "\\setlength{\\tabcolsep}{4pt}",
  "\\begin{tabular}{@{}lllllr@{}}", "\\toprule",
  "Source, sample & Language & $N$ & Method & Words/h & SD(log rate) \\\\",
  "\\midrule",
  "\\multicolumn{6}{l}{\\textit{Literature: all-adult tokens per waking hour, Western samples}} \\\\",
  row(lit |> arrange(source, sample)),
  sprintf("\\multicolumn{6}{l}{\\textit{This paper: raw SD of children's mean log rate within dataset (pooled %.2f)}} \\\\", a$input_ref$pooled_raw_sd),
  row(ours |> arrange(sample)),
  "\\multicolumn{6}{l}{\\textit{This paper: measurement model, noise-corrected (95\\% posterior interval)}} \\\\",
  sprintf("Joint io/proc fit, four datasets & US English & %s & LENA + head-cam & -- & %.2f [%.2f, %.2f] \\\\",
          num(sum(ours$n)), sr_model$med, sr_model$lo, sr_model$hi),
  "\\bottomrule", "\\end{tabular}")
writeLines(lines2, file.path(OUT, "sigma_r_evidence.tex"))
cat(sprintf("wrote sigma_r_ranges.tex (%d rows) and sigma_r_evidence.tex (%d literature + %d own rows)\n", nrow(rng), nrow(lit), nrow(ours)))
cat(sprintf("reference rate %.0f words/h; literature single-sample SD median %.3f (n = %d); pooled raw SD ours %.3f; model sigma_r %.2f [%.2f, %.2f]\n",
            ref, lit_median, sum(single), a$input_ref$pooled_raw_sd, sr_model$med, sr_model$lo, sr_model$hi))
print(as.data.frame(rng |> mutate(across(c(lo, hi), round), across(c(per_sd, ratio, en, no), ~ round(.x, 2))) |> select(-role)))
print(as.data.frame(lit |> select(source, sample, n, rate, sd)), right = FALSE)
