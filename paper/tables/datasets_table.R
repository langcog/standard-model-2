## Datasets table (SI Table S1) as a LaTeX booktabs tabular, generated from the
## committed cache paper/cache/table1_datasets.csv (built by paper/build_table1.R
## from the fitted bundles + Wordbank extracts). Writes
## paper/tables/out/datasets_table.tex, meant to be \input{} inside a table
## environment in the Overleaf SI (needs \usepackage{booktabs}).
## Three groups: Wordbank longitudinal (imputed fits + demographic BLUP arm),
## the six input / processing datasets, Wordbank cross-sectional (one
## administration per child). Counts are the analysis samples after all
## exclusions. Run: Rscript paper/tables/datasets_table.R
suppressPackageStartupMessages({library(here); library(dplyr); library(readr)})

t1  <- read_csv(here("paper", "cache", "table1_datasets.csv"), show_col_types = FALSE)
OUT <- here("paper", "tables", "out"); dir.create(OUT, recursive = TRUE, showWarnings = FALSE)

## Source strings. The cache still carries "(20XX)" placeholders for the three
## English Wordbank longitudinal datasets: fill in here once the bib is settled
## (map from the cache's citation string to the printed source).
SOURCE <- c(
  "Thal et al. (20XX)"     = "Thal et al.\\ [year TODO]",
  "Smith et al. (20XX)"    = "Smith et al.\\ [year TODO]",
  "Marchman et al. (20XX)" = "Marchman et al.\\ [year TODO]",
  "Frank et al. (2017)"    = "Wordbank")
INPUT <- c(headcam = "head-cam", LENA = "LENA", "")
tex <- function(x) gsub("&", "\\\\&", x, fixed = FALSE)
num <- function(x) ifelse(is.na(x), "--", format(x, big.mark = ",", trim = TRUE))
row <- function(d) {
  src  <- tex(ifelse(d$citation %in% names(SOURCE), SOURCE[d$citation], d$citation))
  ages <- sprintf("%g--%g", d$min_age, d$max_age)
  inp  <- ifelse(d$input == "" | is.na(d$input), "--", INPUT[d$input])
  sprintf("%s & %s & %s & %s & %s & %.1f & %s & %s & %s \\\\",
          tex(d$language), src, num(d$n), num(d$n_admins), ages, d$mean_age,
          inp, num(d$n_recordings), num(d$n_lwl))
}
group <- function(title) sprintf("\\addlinespace[2pt]\\multicolumn{9}{l}{\\textit{%s}} \\\\[1pt]", title)

lines <- c(
  "% Generated by paper/tables/datasets_table.R from paper/cache/table1_datasets.csv -- do not edit by hand.",
  "\\begin{tabular}{llrrrrlrr}",
  "\\toprule",
  "Language & Source & $N$ & Admin. & Ages (mo) & Mean & Input & Rec. & LWL \\\\",
  "\\midrule",
  group("Wordbank longitudinal (imputed-input fits; demographic BLUP arm)"),
  row(t1 |> filter(group == "Wordbank longitudinal")),
  group("Input / processing (joint and separate measurement-model fits)"),
  row(t1 |> filter(group == "Input / processing")),
  group("Wordbank cross-sectional (Frank et al., 2017; one administration per child)"),
  row(t1 |> filter(group == "Wordbank cross-sectional") |> arrange(language)),
  "\\bottomrule",
  "\\end{tabular}")
writeLines(lines, file.path(OUT, "datasets_table.tex"))
cat(sprintf("wrote %s (%d data rows)\n", file.path(OUT, "datasets_table.tex"), nrow(t1)))
